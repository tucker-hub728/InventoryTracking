"""SQLAlchemy declarative base.

All ORM models inherit from ``Base``. The metadata's naming convention is
set explicitly so that constraint names are predictable in Alembic
migrations (no ``ix_abc123def`` autogenerated noise) and match the
convention documented in the schema spec.

Models will be added in subsequent modules. For now this file just declares
the base; importing it has no side effects.
"""

from __future__ import annotations

from sqlalchemy import MetaData
from sqlalchemy.orm import DeclarativeBase

# Constraint naming convention matches docs/backend-data-structure.md §2.
# Alembic uses this to generate human-readable constraint names.
NAMING_CONVENTION = {
    "ix": "ix_%(table_name)s_%(column_0_N_name)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    """Declarative base for all ORM models.

    Schema-per-module organisation is handled via ``__table_args__`` on each
    model (e.g. ``__table_args__ = {"schema": "app"}``), not by sub-classing.
    """

    metadata = MetaData(naming_convention=NAMING_CONVENTION)
